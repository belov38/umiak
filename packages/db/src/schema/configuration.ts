import { sql } from "drizzle-orm";
import {
	boolean,
	jsonb,
	numeric,
	pgSchema,
	text,
	timestamp,
	uuid,
} from "drizzle-orm/pg-core";

const runtime = pgSchema("runtime");
export const configUsers = runtime.table("users", {
	id: uuid("id").primaryKey().default(sql`uuidv7()`),
	email: text("email").notNull(),
	name: text("name"),
	idpSubject: text("idp_subject"),
	preferredUsername: text("preferred_username"),
	groups: jsonb("groups"),
	isOperator: boolean("is_operator").default(false).notNull(),
	active: boolean("active").default(true).notNull(),
	deactivatedReason: text("deactivated_reason"),
	deactivatedAt: timestamp("deactivated_at", { withTimezone: true }),
	defaultTeamId: uuid("default_team_id"),
	personalTeamId: uuid("personal_team_id"),
	lastLoginAt: timestamp("last_login_at", { withTimezone: true }),
	updatedAt: timestamp("updated_at", { withTimezone: true }).notNull(),
	createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
});
export const configTeams = runtime.table("teams", {
	id: uuid("id").primaryKey().default(sql`uuidv7()`),
	name: text("name").notNull(),
	personal: boolean("personal"),
	createdById: uuid("created_by_id"),
	quotaMaxActiveSandboxes: numeric("quota_max_active_sandboxes"),
	quotaMaxRamMb: numeric("quota_max_ram_mb"),
	quotaMaxSavedSnapshots: numeric("quota_max_saved_snapshots"),
	updatedAt: timestamp("updated_at", { withTimezone: true }).notNull(),
	createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
});
export const configMemberships = runtime.table("memberships", {
	id: uuid("id").primaryKey().default(sql`uuidv7()`),
	userId: uuid("user_id").notNull(),
	teamId: uuid("team_id").notNull(),
	role: text("role").notNull(),
	invitedById: uuid("invited_by_id"),
	updatedAt: timestamp("updated_at", { withTimezone: true }).notNull(),
	createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
});
export const configApiKeys = runtime.table("api_keys", {
	id: uuid("id").primaryKey().default(sql`uuidv7()`),
	name: text("name").notNull(),
	teamId: uuid("team_id"),
	createdById: uuid("created_by_id"),
	kind: text("kind").notNull(),
	sandbox: text("sandbox"),
	secretHash: text("secret_hash").notNull(),
	prefix: text("prefix").notNull(),
	last4: text("last4").notNull(),
	scopes: jsonb("scopes").notNull(),
	expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
	createdVia: text("created_via").notNull(),
	lastUsedAt: timestamp("last_used_at", { withTimezone: true }),
	rotatedAt: timestamp("rotated_at", { withTimezone: true }),
	revokedAt: timestamp("revoked_at", { withTimezone: true }),
	revokedById: uuid("revoked_by_id"),
	revokedByKeyId: uuid("revoked_by_key_id"),
	updatedAt: timestamp("updated_at", { withTimezone: true }).notNull(),
	createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
});
export const configSshKeys = runtime.table("ssh_keys", {
	id: uuid("id").primaryKey().default(sql`uuidv7()`),
	userId: uuid("user_id").notNull(),
	name: text("name").notNull(),
	publicKey: text("public_key").notNull(),
	fingerprint: text("fingerprint").notNull(),
	type: text("type").notNull(),
	lastUsedAt: timestamp("last_used_at", { withTimezone: true }),
	updatedAt: timestamp("updated_at", { withTimezone: true }).notNull(),
	createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
});
export const configTemplates = runtime.table("templates", {
	id: uuid("id").primaryKey().default(sql`uuidv7()`),
	slug: text("slug").notNull(),
	name: text("name"),
	description: text("description"),
	os: text("os").notNull(),
	enabled: boolean("enabled"),
	defaultSize: text("default_size").notNull(),
	allowedSizes: jsonb("allowed_sizes").notNull(),
	loginUser: text("login_user"),
	capabilities: jsonb("capabilities"),
	sortOrder: numeric("sort_order"),
	updatedAt: timestamp("updated_at", { withTimezone: true }).notNull(),
	createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
});
export const configSizes = runtime.table("sizes", {
	id: uuid("id").primaryKey().default(sql`uuidv7()`),
	slug: text("slug").notNull(),
	vcpu: numeric("vcpu").notNull(),
	memoryMb: numeric("memory_mb").notNull(),
	sortOrder: numeric("sort_order"),
	updatedAt: timestamp("updated_at", { withTimezone: true }).notNull(),
	createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
});
export const configPlatformDefaults = runtime.table("platform_defaults", {
	id: uuid("id").primaryKey().default(sql`uuidv7()`),
	ttlSeconds: numeric("ttl_seconds"),
	maxTtlSeconds: numeric("max_ttl_seconds").notNull(),
	idleTimeoutSeconds: numeric("idle_timeout_seconds"),
	stoppedRetentionDays: numeric("stopped_retention_days"),
	errorRetentionDays: numeric("error_retention_days").notNull(),
	recoverMinIntervalSeconds: numeric("recover_min_interval_seconds").notNull(),
	defaultTemplate: text("default_template").notNull(),
	publicPortsEnabled: boolean("public_ports_enabled"),
	rateLimitsRequestsPerSecond: numeric("rate_limits_requests_per_second"),
	rateLimitsBurst: numeric("rate_limits_burst"),
	rateLimitsStartsPerMinute: numeric("rate_limits_starts_per_minute"),
	defaultQuotaMaxActiveSandboxes: numeric("default_quota_max_active_sandboxes"),
	defaultQuotaMaxRamMb: numeric("default_quota_max_ram_mb"),
	defaultQuotaMaxSavedSnapshots: numeric("default_quota_max_saved_snapshots"),
	newSharedTeamQuotaMaxActiveSandboxes: numeric(
		"new_shared_team_quota_max_active_sandboxes",
	),
	newSharedTeamQuotaMaxRamMb: numeric("new_shared_team_quota_max_ram_mb"),
	newSharedTeamQuotaMaxSavedSnapshots: numeric(
		"new_shared_team_quota_max_saved_snapshots",
	),
	maxOwnedTeamsPerUser: numeric("max_owned_teams_per_user"),
	updatedAt: timestamp("updated_at", { withTimezone: true }),
	createdAt: timestamp("created_at", { withTimezone: true }),
	publicDesktopEnabled: boolean("public_desktop_enabled"),
});
export const configurationTables = {
	configUsers,
	configTeams,
	configMemberships,
	configApiKeys,
	configSshKeys,
	configTemplates,
	configSizes,
	configPlatformDefaults,
};
